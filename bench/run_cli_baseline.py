#!/usr/bin/env python3
"""Run one local llama.cpp CLI baseline and persist comparable metrics.

The runner is intentionally dependency-free so it can be copied unchanged to
Termux. It records a durable attempt before launching inference, measures TTFT
as the elapsed time until the first generated byte, and uses llama.cpp's own
performance report for decode tokens/second.
"""

from __future__ import annotations

import argparse
import os
import re
import selectors
import shlex
import subprocess
import time
from pathlib import Path

from edgesplit_bench import finish_attempt, log_run, start_attempt


DECODE_RE = re.compile(
    r"eval time\s*=\s*[\d.]+\s*ms\s*/\s*(\d+) tokens.*?,\s*([\d.]+) tokens per second",
    re.IGNORECASE,
)
PROMPT_RE = re.compile(
    r"prompt eval time\s*=\s*[\d.]+\s*ms\s*/\s*(\d+) tokens.*?,\s*([\d.]+) tokens per second",
    re.IGNORECASE,
)
GENERATION_TPS_RE = re.compile(r"Generation:\s*([\d.]+)\s*t/s", re.IGNORECASE)


def positive_int(value: str) -> int:
    parsed = int(value)
    if parsed <= 0:
        raise argparse.ArgumentTypeError("must be greater than zero")
    return parsed


def build_command(args: argparse.Namespace) -> list[str]:
    command = [
        str(args.llama_cli), "--model", str(args.model), "--prompt", args.prompt,
        "--n-predict", str(args.output_tokens), "--perf", "--simple-io",
        "--no-warmup", "--single-turn",
    ]
    if args.threads is not None:
        command.extend(["--threads", str(args.threads)])
    if args.threads_batch is not None:
        command.extend(["--threads-batch", str(args.threads_batch)])
    if args.gpu_layers is not None:
        command.extend(["--n-gpu-layers", str(args.gpu_layers)])
    command.extend(args.extra_arg)
    return command


def run(
    command: list[str], args: argparse.Namespace, *, env: dict[str, str] | None = None,
) -> tuple[float, float, int, str]:
    started = time.perf_counter()
    process = subprocess.Popen(
        command, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        text=True, bufsize=1, env=env,
    )
    assert process.stdout is not None and process.stderr is not None
    selector = selectors.DefaultSelector()
    selector.register(process.stdout, selectors.EVENT_READ, "stdout")
    selector.register(process.stderr, selectors.EVENT_READ, "stderr")
    first_byte_at: float | None = None
    stdout: list[str] = []
    stderr: list[str] = []

    prompt_echo_seen = False
    prompt_echo = f"> {args.prompt}"
    while selector.get_map():
        for key, _ in selector.select(timeout=0.1):
            character = key.fileobj.read(1)
            if not character:
                selector.unregister(key.fileobj)
                continue
            if key.data == "stdout":
                stdout.append(character)
                if not prompt_echo_seen:
                    prompt_echo_seen = prompt_echo in "".join(stdout)
                elif first_byte_at is None and not character.isspace():
                    first_byte_at = time.perf_counter()
            else:
                stderr.append(character)
    exit_code = process.wait()
    stdout_text = "".join(stdout)
    combined = "".join(stderr) + stdout_text
    if exit_code:
        raise RuntimeError(f"llama-cli exited {exit_code}:\n{combined}")
    match = DECODE_RE.search(combined)
    compact = GENERATION_TPS_RE.search(combined)
    if match:
        decoded_tokens = int(match.group(1))
        tokens_per_sec = float(match.group(2))
    elif compact:
        decoded_tokens = args.output_tokens
        tokens_per_sec = float(compact.group(1))
    else:
        raise RuntimeError("llama.cpp decode timing was not found:\n" + combined)
    if decoded_tokens <= 0:
        raise RuntimeError("llama.cpp reported zero decoded tokens")
    if first_byte_at is None:
        raise RuntimeError("llama-cli produced no generated output")
    prompt = PROMPT_RE.search(combined)
    prompt_tokens = int(prompt.group(1)) if prompt else len(args.prompt.split())
    return first_byte_at - started, tokens_per_sec, prompt_tokens, stdout_text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, default=Path("bench/edgesplit.sqlite3"))
    parser.add_argument("--llama-cli", type=Path, required=True)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--device", required=True)
    parser.add_argument("--config", choices=("laptop-only", "phone-only"), required=True)
    parser.add_argument("--model-name", required=True)
    parser.add_argument("--quant", required=True)
    parser.add_argument("--llama-cpp-commit", required=True)
    parser.add_argument("--prompt", required=True)
    parser.add_argument("--output-tokens", type=positive_int, default=64)
    parser.add_argument("--threads", type=positive_int)
    parser.add_argument("--threads-batch", type=positive_int)
    parser.add_argument("--gpu-layers", type=int)
    parser.add_argument("--power-draw-mw", type=float)
    parser.add_argument("--extra-arg", action="append", default=[])
    args = parser.parse_args()
    if not args.llama_cli.is_file() or not os.access(args.llama_cli, os.X_OK):
        parser.error(f"llama-cli is not executable: {args.llama_cli}")
    if not args.model.is_file():
        parser.error(f"model is not a file: {args.model}")

    command = build_command(args)
    command_text = shlex.join(command)
    attempt_values = {
        "device": args.device,
        "config": args.config,
        "model": args.model_name,
        "quant": args.quant,
        "prompt_len": str(len(args.prompt.split())),
        "output_len": str(args.output_tokens),
        "llama_cpp_commit": args.llama_cpp_commit,
    }
    attempt_id = start_attempt(args.db, attempt_values, command_text)
    print(f"attempt_id={attempt_id} command={command_text}", flush=True)
    try:
        ttft, tokens_per_sec, prompt_tokens, _ = run(command, args)
        notes = (
            "ttft=first generated byte after prompt echo; tps=llama.cpp timing; "
            f"threads={args.threads if args.threads is not None else 'default'}; "
            f"threads_batch={args.threads_batch if args.threads_batch is not None else 'default'}"
        )
        row_id = log_run(args.db, {
            "device": args.device,
            "config": args.config,
            "model": args.model_name,
            "quant": args.quant,
            "prompt_len": str(prompt_tokens),
            "output_len": str(args.output_tokens),
            "ttft": f"{ttft:.6f}",
            "tokens_per_sec": f"{tokens_per_sec:.6f}",
            "power_draw_mw": (f"{args.power_draw_mw:.3f}"
                              if args.power_draw_mw is not None else ""),
            "llama_cpp_commit": args.llama_cpp_commit,
            "notes": notes,
        })
    except BaseException as exc:
        finish_attempt(args.db, attempt_id, "failed", error=f"{type(exc).__name__}: {exc}")
        raise
    finish_attempt(args.db, attempt_id, "completed", benchmark_run_id=row_id)
    print(f"row_id={row_id} ttft={ttft:.3f}s decode_tps={tokens_per_sec:.3f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
